// ============================================================
// Helper: resolve icon name for a file
// ============================================================

function resolveFileIcon(filename: string): string {
  const lower = filename.toLowerCase();

  // exact filename match first
  if (lower in filenameMap) return filenameMap[lower];

  // extension-based: check compound extensions first (e.g. ".d.ts")
  for (const ext of Object.keys(extMap).sort((a, b) => b.length - a.length)) {
    if (lower.endsWith("." + ext)) return extMap[ext];
  }

  // check for patterns
  if (
    lower.includes(".spec.") ||
    lower.includes(".test.") ||
    lower.endsWith(".spec.ts") ||
    lower.endsWith(".test.ts") ||
    lower.endsWith(".spec.js") ||
    lower.endsWith(".test.js")
  ) {
    if (lower.includes("tsx") || lower.includes("jsx")) return "test_jsx";
    return "test_ts";
  }

  if (lower.endsWith(".env") || lower.startsWith(".env")) return "env";
  if (lower.startsWith("dockerfile")) return "docker";
  if (lower.startsWith("docker-compose")) return "docker_compose";

  // stories
  if (lower.includes(".stories.")) return "storybook";

  return "file";
}

// ============================================================
// Helper: resolve folder icon name
// ============================================================

function resolveFolderIcon(folderName: string): string {
  const lower = folderName.toLowerCase();
  return folderMap[lower] ?? "folder";
}

// ============================================================
// Icon SVG component
// ============================================================

const FileIcon = memo(function FileIcon({
  filename,
  isFolder = false,
  size = 14,
  className,
}: FileIconProps) {
  const name = isFolder ? resolveFolderIcon(filename) : resolveFileIcon(filename);
  const data = iconData[name] ?? iconData[isFolder ? "folder" : "file"];
  const color = iconColors[name] ?? DEFAULT_COLOR;

  return (
    <svg
      width={size}
      height={size}
      viewBox={data.viewBox}
      className={className}
      style={{ flexShrink: 0 }}
      fill="none"
      xmlns="http://www.w3.org/2000/svg"
    >
      {data.paths.map((p, i) => (
        <path key={i} d={p.d} fill={p.fill ?? color} />
      ))}
    </svg>
  );
});

