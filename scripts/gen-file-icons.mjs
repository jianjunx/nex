// 构建期 codegen:从 material-icon-theme 官方包生成 Nex 的文件图标资源。
//
// 输出:
//   1. public/file-icons/<icon>.svg —— 被引用图标的 SVG 子集(按图标名命名)
//   2. src/features/files/iconManifest.generated.ts —— 扩展名/文件名/文件夹名 → 图标名映射表
//
// 用法:pnpm gen:icons(已挂进 build 链;生成物提交 git,dev 模式零依赖)

import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

const pkgDir = path.dirname(require.resolve("material-icon-theme/package.json"));
const pkgVersion = JSON.parse(fs.readFileSync(path.join(pkgDir, "package.json"), "utf8")).version;
const srcIconsDir = path.join(pkgDir, "icons");
const outIconsDir = path.join(repoRoot, "public", "file-icons");
const outFile = path.join(repoRoot, "src", "features", "files", "iconManifest.generated.ts");

const { generateManifest } = await import("material-icon-theme");
// 中性配置:不启用任何框架 icon pack,保证 jsx/vue 等拿到通用图标。
const manifest = generateManifest({});

// ---------------------------------------------------------------------------
// 1) 校验 open 变体约定:folderNamesExpanded[k] === folderNames[k] + "-open"
//    resolveIcon 依赖该约定推导展开态图标,约定破坏时立刻报错。
// ---------------------------------------------------------------------------
const openMismatches = Object.entries(manifest.folderNamesExpanded ?? {})
  .filter(([k, v]) => v !== manifest.folderNames[k] + "-open");
if (openMismatches.length > 0) {
  console.error("✗ folderNamesExpanded '-open' 约定被破坏,样例:");
  for (const [k, v] of openMismatches.slice(0, 5)) {
    console.error(`    ${k}: ${manifest.folderNames[k]} -> ${v}`);
  }
  process.exit(1);
}

// ---------------------------------------------------------------------------
// 2) 拆分映射表;收集全部被引用的图标名
// ---------------------------------------------------------------------------
const used = new Set();
const take = (table) => {
  const out = {};
  for (const [k, icon] of Object.entries(table ?? {})) {
    out[k] = icon;
    used.add(icon);
  }
  return out;
};

const extMap = {};         // 单段扩展名(O(1) 查表)
const compoundExtMap = {}; // 含点的复合扩展名(如 ts.map / schema.json)
for (const [k, icon] of Object.entries(manifest.fileExtensions ?? {})) {
  (k.includes(".") ? compoundExtMap : extMap)[k] = icon;
  used.add(icon);
}
const fileNameMap = take(manifest.fileNames);
const folderNameMap = take(manifest.folderNames);
// 展开态图标由 resolveIcon 推导为 图标名 + "-open"(约定已在上面校验),同样要拷贝。
for (const icon of Object.values(folderNameMap)) used.add(icon + "-open");
for (const name of [manifest.file, manifest.folder, manifest.folderExpanded, manifest.rootFolder, manifest.rootFolderExpanded]) {
  if (name) used.add(name);
}

// ---------------------------------------------------------------------------
// 3) 拷贝 SVG:清空目标目录,逐图标按 iconDefinitions 定位源文件
// ---------------------------------------------------------------------------
fs.rmSync(outIconsDir, { recursive: true, force: true });
fs.mkdirSync(outIconsDir, { recursive: true });

const missing = [];
for (const name of [...used].sort()) {
  const def = manifest.iconDefinitions?.[name];
  const svgFile = def ? path.basename(typeof def === "string" ? def : def.iconPath) : null;
  if (!svgFile) {
    missing.push(`${name} (无 iconDefinitions 条目)`);
    continue;
  }
  const src = path.join(srcIconsDir, svgFile);
  if (!fs.existsSync(src)) {
    missing.push(`${name} -> ${svgFile} (SVG 不存在)`);
    continue;
  }
  fs.copyFileSync(src, path.join(outIconsDir, `${name}.svg`));
}
if (missing.length > 0) {
  console.error(`✗ ${missing.length} 个图标无法定位:`);
  for (const m of missing.slice(0, 20)) console.error(`    ${m}`);
  process.exit(1);
}

// ---------------------------------------------------------------------------
// 4) 生成 TS 映射表(键排序保证稳定 diff)
// ---------------------------------------------------------------------------
const sorted = (obj) =>
  Object.fromEntries(Object.entries(obj).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));

const ts = `/* eslint-disable */
// @generated by scripts/gen-file-icons.mjs from material-icon-theme@${pkgVersion} — do not edit.
// 运行 \`pnpm gen:icons\` 重新生成。

/** 默认文件图标 */
export const defaultFileIcon = ${JSON.stringify(manifest.file)};
/** 默认文件夹图标(折叠态) */
export const defaultFolderIcon = ${JSON.stringify(manifest.folder)};
/** 默认文件夹图标(展开态) */
export const defaultFolderOpenIcon = ${JSON.stringify(manifest.folderExpanded)};
/** 项目根文件夹图标(折叠态) */
export const defaultRootFolderIcon = ${JSON.stringify(manifest.rootFolder)};
/** 项目根文件夹图标(展开态) */
export const defaultRootFolderOpenIcon = ${JSON.stringify(manifest.rootFolderExpanded)};

/** 单段扩展名 → 图标名(键不含点,全小写) */
export const extMap: Record<string, string> = ${JSON.stringify(sorted(extMap))};

/** 复合扩展名 → 图标名(键含点,如 "schema.json",全小写) */
export const compoundExtMap: Record<string, string> = ${JSON.stringify(sorted(compoundExtMap))};

/** 精确文件名 → 图标名(全小写) */
export const fileNameMap: Record<string, string> = ${JSON.stringify(sorted(fileNameMap))};

/** 文件夹名 → 图标名(全小写);展开态恒为 图标名 + "-open" */
export const folderNameMap: Record<string, string> = ${JSON.stringify(sorted(folderNameMap))};
`;

fs.writeFileSync(outFile, ts, "utf8");

// ---------------------------------------------------------------------------
// 5) 统计
// ---------------------------------------------------------------------------
console.log(`✓ material-icon-theme@${pkgVersion}`);
console.log(`  SVG: ${used.size} 个 → public/file-icons/`);
console.log(`  扩展名: ${Object.keys(extMap).length} 单段 + ${Object.keys(compoundExtMap).length} 复合`);
console.log(`  文件名: ${Object.keys(fileNameMap).length};文件夹名: ${Object.keys(folderNameMap).length}`);
console.log(`  TS: ${path.relative(repoRoot, outFile)} (${(fs.statSync(outFile).size / 1024).toFixed(0)} KB)`);
